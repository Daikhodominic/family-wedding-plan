import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page(viewport={'width':1440,'height':900})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('http://localhost:8765/index.html?demo#/w/charani/plan?view=map'); await pg.wait_for_timeout(1000)
        area = pg.locator('.marea').first
        names = lambda: area.locator('.mnode .mt').all_inner_texts()
        print('before', await names())
        await area.locator('.mgap').first.click(); await pg.wait_for_timeout(200)
        await pg.fill('.modal input', 'Inserted in between'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(700)
        print('after gap', await names())
        await area.locator('.madd').click(); await pg.fill('.modal input', 'Added at the end'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(700)
        print('after end', await names())
        n0 = await pg.locator('.marea').count()
        await pg.locator('.madd.area').first.click(); await pg.fill('.modal input', 'New test area'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(700)
        print('areas', n0, '->', await pg.locator('.marea').count())
        s0 = await pg.locator('.mstage').count()
        await pg.locator('.madd.stage').click(); await pg.fill('.modal input', 'Engagement'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(700)
        print('stages', s0, '->', await pg.locator('.mstage').count())
        await pg.locator('.marea:has-text("New test area") .marea-x').click(); await pg.wait_for_timeout(200)
        await pg.click('.modal-actions .btn:has-text("Move to the Bin")'); await pg.wait_for_timeout(700)
        print('after remove', await pg.locator('.marea:has-text("New test area")').count())
        await pg.screenshot(path='shots/map_add.png')
        await area.locator('.mnode').first.click(); await pg.wait_for_timeout(600)
        await pg.click('button:has-text("Add a step after this")'); await pg.fill('.modal input', 'From the drawer'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(800)
        print('after drawer', await names())
        await pg.goto('http://localhost:8765/index.html?demo#/w/charani/plan?view=list'); await pg.wait_for_timeout(800)
        print('list shows', await pg.locator('.area').first.locator('.step').count() if await pg.locator('.step').count() else 'n/a')
        pg2=await b.new_page(viewport={'width':390,'height':844}); await pg2.goto('http://localhost:8765/index.html?demo#/w/charani/plan?view=map'); await pg2.wait_for_timeout(900)
        await pg2.screenshot(path='shots/map_add_m.png')
        print('errors', errs); await b.close()
asyncio.run(main())
